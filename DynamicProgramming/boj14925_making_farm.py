# BOJ 14925 - 목장 건설하기
#
# 문제 핵심:
# 주어진 M x N 땅에서, 값이 0인 칸만 이용해서 만들 수 있는
# 가장 큰 "정사각형"의 한 변 길이를 구하는 문제이다.
#
# 즉,
# - 0  : 목장을 지을 수 있는 빈 땅
# - 0이 아닌 값 : 나무나 바위가 있는 장애물
#
# 우리가 찾아야 하는 것:
# "모든 칸이 0으로만 이루어진 가장 큰 정사각형의 변 길이"
#
# ------------------------------------------------------------
# [왜 DP인가?]
#
# 어떤 칸 (i, j)를 정사각형의 "오른쪽 아래 끝점"이라고 생각해보자.
#
# 만약 (i, j)까지 포함해서 한 변 길이가 k인 정사각형을 만들고 싶다면,
# 그 바로 위, 바로 왼쪽, 왼쪽 위 대각선 쪽에도
# 최소한 k-1 크기의 정사각형 정보가 있어야 한다.
#
# 즉, 현재 칸이 0일 때:
#
#   dp[i][j] = min(
#       dp[i-1][j],     # 위쪽을 오른쪽 아래로 하는 정사각형 크기
#       dp[i][j-1],     # 왼쪽을 오른쪽 아래로 하는 정사각형 크기
#       dp[i-1][j-1]    # 왼쪽 위 대각선을 오른쪽 아래로 하는 정사각형 크기
#   ) + 1
#
# 왜 min 이냐?
# -> 세 방향 중 하나라도 작으면, 그보다 더 큰 정사각형은 만들 수 없기 때문이다.
#
# 예를 들어:
# 위 = 3, 왼쪽 = 3, 왼쪽위 = 1 이라면
# 현재 칸에서 만들 수 있는 최대 정사각형은 2가 된다.
# 왜냐하면 대각선 방향이 1밖에 못 받쳐주기 때문이다.
#
# ------------------------------------------------------------
# [dp 배열의 의미]
#
# dp[i][j] =
#   "좌표 (i, j)를 오른쪽 아래 꼭짓점으로 하는
#    만들 수 있는 가장 큰 정사각형의 한 변 길이"
#
# 예를 들어 dp[i][j] = 4 라면,
# (i, j)를 오른쪽 아래 끝점으로 하는 4 x 4 정사각형이
# 모두 0으로 이루어져 있다는 뜻이다.
#
# ------------------------------------------------------------
# [첫 행 / 첫 열 처리]
#
# 첫 행(i == 0)이나 첫 열(j == 0)은
# 위, 왼쪽, 왼쪽위 값을 모두 활용할 수 없다.
#
# 그래서 이 경우에는:
# - 현재 칸이 0이면 1 x 1 정사각형은 만들 수 있으므로 dp = 1
# - 현재 칸이 0이 아니면 애초에 목장을 못 지으므로 dp = 0
#
# ------------------------------------------------------------
# [시간복잡도]
#
# 모든 칸을 한 번씩만 확인하므로:
# O(M x N)
#
# 이는 완전탐색처럼 모든 정사각형을 직접 검사하는 방식보다 훨씬 효율적이다.
#
# ------------------------------------------------------------

# M: 행 개수
# N: 열 개수
M, N = map(int, input().split())

# 입력으로 주어진 목장 땅 정보
# grid[i][j] == 0 이면 빈 땅
# grid[i][j] != 0 이면 장애물(나무/바위)
grid = [list(map(int, input().split())) for _ in range(M)]

# dp 배열 생성
# dp[i][j]는 (i, j)를 오른쪽 아래 꼭짓점으로 하는
# 가장 큰 정사각형의 변 길이를 저장한다.
dp = [[0] * N for _ in range(M)]

# 지금까지 찾은 가장 큰 정사각형의 한 변 길이
max_width = 0

# 전체 격자를 순회하면서 각 칸을 "정사각형의 오른쪽 아래 끝점"이라고 가정하고 계산
for i in range(M):
    for j in range(N):

        # 현재 칸이 0일 때만 목장 후보가 될 수 있다.
        # 장애물이 있으면 이 칸을 포함하는 정사각형은 만들 수 없다.
        if grid[i][j] == 0:

            # 첫 행 또는 첫 열이라면
            # 만들 수 있는 최대 정사각형은 자기 자신만 포함하는 1 x 1 뿐이다.
            if i == 0 or j == 0:
                dp[i][j] = 1

            # 첫 행, 첫 열이 아니라면
            # 위 / 왼쪽 / 왼쪽 위 대각선의 정사각형 크기를 참고해서
            # 현재 칸까지 확장 가능한 최대 정사각형 크기를 구한다.
            else:
                dp[i][j] = (
                    min(
                        dp[i - 1][j],  # 위쪽 칸 기준 최대 정사각형
                        dp[i][j - 1],  # 왼쪽 칸 기준 최대 정사각형
                        dp[i - 1][j - 1],  # 왼쪽 위 대각선 칸 기준 최대 정사각형
                    )
                    + 1
                )

            # 현재 칸까지 계산한 정사각형 크기로 전체 최댓값 갱신
            max_width = max(max_width, dp[i][j])

# 최종적으로 가장 큰 정사각형의 변 길이 출력
print(max_width)
